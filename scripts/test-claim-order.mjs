// 「前面自报平民、后面跳神」的定档。
//
// 起因：这个组合几乎每局都被当成铁狼点。按本项目自己的标尺它不配铁证：
//   · 顺序本身狼和好人都做得出来；
//   · 白天发言提示明确授权藏身份的神职"使用符合规则的公开假口径"——这个行为常常
//     正是教学层自己批准的打法；
//   · 他一句"我当时在藏"就能回应。
//
// ★ 这条改过两次，两次的教训都要留在测试里：
//   第一版：替代打法自相矛盾——"当平民时说我什么都不知道，补跳后却报得出刀口"正是理由②
//     批准的伪装，他一句"我在藏"就解释掉了。改为：别对他的【话】，对他的【行动】
//     （伪装允许说假话，但不需要逆着自己的信息投票）。这条修正是对的，保留。
//   第二版：一局实测里做这件事的恰好是狼，我据此把它改回"C级不是零，被查杀后才穿衣服的狼
//     更常走这条路，五五开时可以打破平局"。这是结果论——一局的翻牌不说明信号有用。
//     而且方向也错了：被查杀后跳神，正是核心层【被查杀之后】要求真神做的事
//     （"你确实是神职：现在就是跳的时刻"）；首置位没有任何信息，装平民是所有身份的默认。
//     所以被查杀后才跳的，连C级都不该留；只有没被逼、主动改口的，才按改口的C级留疑。
import assert from 'node:assert/strict';
import fs from 'node:fs';

const FILES = ['index.html', 'en/index.html'];

function core(file) {
  const src = fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
  const a = src.indexOf('const WB_CORE_COMPACT = `');
  const b = src.indexOf('\n\nconst WB_RULES_COMPACT', a);
  assert.ok(a >= 0 && b > a, `${file}: WB_CORE_COMPACT 未找到`);
  return src.slice(a, b);
}

for (const file of FILES) {
  const c = core(file);
  const src = fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');

  // ── 1. ★ 定档：不能当狼点；被查杀后才跳的，连C级都不留 ─────────────────────
  assert.ok(c.includes('【「前面自报平民、后面跳神」不能当狼点】'), `${file}: 没有给这个组合定档`);
  // 第二版的结果论措辞不能回流
  assert.ok(!c.includes('但C级不是零'), `${file}: 第二版"C级不是零"的结果论回流了`);
  assert.ok(!c.includes('被查杀后才穿衣服的狼确实比真神更常走这条路'), `${file}: 没有依据的似然比断言回流了`);
  assert.ok(!c.includes('打破平局的那一点重量'), `${file}: "五五开时打破平局"回流了`);
  assert.match(c, /装平民是任何身份的默认打法/, `${file}: 缺少理由①：首置位装平民是默认`);
  assert.match(c, /如果他是【被查杀之后】才跳的，那他做的恰好是本教学层要求真神做的事/, `${file}: 缺少理由②：被查杀就跳是我们教的`);
  assert.match(c, /这种情况下连C级的那点疑都不该留/, `${file}: 被查杀后跳神仍被留了疑`);
  assert.match(c, /只有他【没被逼、自己主动】改口时，才按改口的C级留个疑/, `${file}: 没有区分主动改口和被逼跳神`);
  // ★ 理由②依赖核心层【被查杀之后】里的这句；它被删了，这条会悬空
  assert.ok(c.includes('你确实是神职：现在就是跳的时刻'), `${file}: 【被查杀之后】里"神职现在就跳"被删了，理由②失去依据`);
  // ── 1b. ★ 换名字逃级 ─────────────────────────────────────────────────────
  // 实测：警长自己的原则是"措辞不定罪、行为定票"，然后把改口改叫"行为账：被查杀之后，
  // 抢一件已经穿在别人身上的衣服"，就用它单独定了票。另外两名好人也用"偷衣服/抢衣服"。
  // 而"偷衣服"的前提是先认定先跳的那个是真的——先后手公式，教学层早就禁止了。
  assert.match(c, /换个名字不会换掉等级/, `${file}: 没有堵住"换名字逃出C级"`);
  assert.match(c, /"行为账""偷衣服""抢一件别人已经穿着的衣服"/, `${file}: 没有点名实测里出现的那几种改名`);
  assert.match(c, /说成"偷衣服"，前提是先认定先跳的那个是真的/, `${file}: 没有拆穿"偷衣服"的循环前提`);
  assert.match(c, /这正是【先后手不是身份公式】禁止的推法/, `${file}: 没有接回先后手那条`);
  assert.match(c, /如果他才是真的，对跳是他唯一能做的事，不是破绽/, `${file}: 没写出真神对跳的必然性`);
  assert.ok(src.includes('【先后手不是身份公式】'), `${file}: 被引用的【先后手不是身份公式】不存在`);

  // ★ 反结果论
  assert.match(c, /某一局里他恰好是狼，不能反过来证明这个信号有用/, `${file}: 缺少反结果论的那句`);
  assert.match(c, /要看的是它在狼身上和好人身上出现得一不一样多，不是这一局翻出来是什么/, `${file}: 没给出正确的判据`);

  // ── 2. 其余理由 ────────────────────────────────────────────────────────────
  assert.match(c, /藏身份的神职也被允许使用公开假口径/, `${file}: 缺少假口径授权那条`);
  assert.match(c, /他一句「我当时在藏」就能回应/, `${file}: 缺少理由③`);
  assert.match(c, /就不能在他推翻它的时候收利息/, `${file}: 缺少内部一致性那条`);

  // ── 3. ★ 替代打法：对行动，不对话 ─────────────────────────────────────────
  // 第一版的例子自相矛盾（拿被批准的伪装去对账），不能回流
  assert.ok(!c.includes('当平民时说「我昨晚什么都'), `${file}: 第一版自相矛盾的例子回流了`);
  assert.match(c, /别对他的【话】，对他的【行动】/, `${file}: 没有把对账对象从话换成行动`);
  assert.match(c, /是被允许的伪装，拿伪装去对账没有意义/, `${file}: 没说明为什么不能对话`);
  assert.match(c, /伪装允许说假话，但不需要逆着自己手里的信息去投票/, `${file}: 没说明为什么行动能对`);
  // 例子必须满足时序：私密信息在前、投票在后，否则违反时点知识账本
  assert.match(c, /验人在前、投票在后，他当时已经知道/, `${file}: 例子没有交代时序，会和时点知识账本打架`);
  assert.match(c, /能不能靠补跳之前已经公开的信息倒填/, `${file}: 缺少倒填检验`);

  // ── 4. 护栏 ────────────────────────────────────────────────────────────────
  assert.match(c, /这条不是禁止怀疑他，是禁止把顺序本身当铁证/, `${file}: 缺少护栏`);

  // ── 5. 它依赖的前提必须还在 ────────────────────────────────────────────────
  assert.ok(c.includes('【身份声明同标尺】'), `${file}: 身份声明同标尺被删了`);
  assert.ok(src.includes('【先后手不是身份公式】'), `${file}: 先后手不是身份公式被删了`);
  assert.ok(
    src.includes('也可以暂缓、部分披露或使用符合规则的公开假口径'),
    `${file}: 藏身份神职的假口径授权被删了，理由②会失去依据`,
  );
  assert.match(c, /C级：单次口误、记错规则、措辞混乱、改口/, `${file}: 改口的 C 级定档被改动了`);
  const iStd = c.indexOf('【身份声明同标尺】');
  const iOrder = c.indexOf('【「前面自报平民、后面跳神」不能当狼点】');
  assert.ok(iOrder > iStd, `${file}: 这条跑到了【身份声明同标尺】前面`);
}

