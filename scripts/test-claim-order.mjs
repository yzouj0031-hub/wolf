// 「前面自报平民、后面跳神」被当成铁狼点。
//
// 这个攻击几乎每局都出现，但按本项目自己的标尺它基本是白攻击：
//   · 【零成本行为不分阵营】——顺序本身狼和好人做起来一样便宜；
//   · 【挑对方无法低成本回应的点】——他一句"我当时在藏"就回应完了；
//   · 【身份声明同标尺】——既然"我是平民"本来就不给信用，推翻它时也不该收利息。
//
// 更要命的是内部矛盾：白天发言提示里明确授权藏身份的神职"使用符合规则的公开假口径"，
// 【先后手不是身份公式】也写了真神可能隐藏到错误票型将成才被迫回应。也就是说这个行为
// 常常正是教学层自己批准的打法，然后别的座位拿它当狼点打。
//
// 拼图原本都在（改口=C级、先后手不是公式、自报平民只是待核验声明、允许假口径），
// 缺的只是把它们接起来的那一条——模型不会自己走完这个推导。
//
// 反过度修正：目标不是给这种人免罪，而是把怀疑从【顺序】挪到【内容】——他当平民时说过
// 的话和补跳后的神职记录对不对得上，以及补跳的记录能否被前置公开信息倒填。
import assert from 'node:assert/strict';
import fs from 'node:fs';

const FILES = ['index.html', 'en/index.html'];

function core(file) {
  const src = fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');
  const a = src.indexOf('const WB_CORE_COMPACT = `');
  const b = src.indexOf('\n\nconst WB_RULES_COMPACT', a);
  assert.ok(a >= 0 && b > a, `${file}: WB_CORE_COMPACT 未找到`);
  return src.slice(a, b);
}

for (const file of FILES) {
  const c = core(file);
  const src = fs.readFileSync(new URL(`../${file}`, import.meta.url), 'utf8');

  // ── 1. ★ 这个组合必须被点名并降级 ──────────────────────────────────────────
  assert.ok(
    c.includes('【「前面自报平民、后面跳神」不是狼点，别拿顺序当证据】'),
    `${file}: 核心层没有点名"前民后神"这个组合`,
  );
  assert.match(c, /但它的证据等级只有C/, `${file}: 没有给出证据等级`);

  // ── 2. ★ 三条理由缺一不可 ────────────────────────────────────────────────
  // 只说"这不是狼点"是个断言，模型在具体局面里会自己推翻它；要接回它已经认的那几把尺子。
  assert.match(c, /顺序本身零成本，狼和好人做起来一样便宜/, `${file}: 缺少理由①：顺序不分阵营`);
  assert.match(c, /本来就被允许使用公开假口径/, `${file}: 缺少理由②：这是教学层自己批准的打法`);
  assert.match(c, /台前才补跳是标准流程，不是破绽/, `${file}: 没写出真神被逼补跳是正常流程`);
  assert.match(
    c,
    /他一句「我当时在藏」就回应完了，你花一整轮换到零/,
    `${file}: 缺少理由③：这是低成本可回应的白攻击`,
  );
  assert.match(c, /【挑对方无法低成本回应的点】点名禁止的白攻击/, `${file}: 没有接回"白攻击"那条`);
  // 内部一致性：不给信用就不能收利息
  assert.match(c, /不能在他推翻它的时候收利息/, `${file}: 没有指出"不给信用却收利息"的双标`);

  // ── 3. ★ 每条"别做X"都要配"那就做Y"——否则只是解除武装 ─────────────────────
  assert.match(
    c,
    /不是「你改口了」，是【你改口之后，前后两套话对不上】/,
    `${file}: 只否掉了旧打法，没给替代打法`,
  );
  assert.match(c, /这是具体事实矛盾，A\/B级，他解释不掉/, `${file}: 替代打法没有给出证据等级`);
  assert.match(
    c,
    /能不能靠补跳之前已经公开的信息倒填/,
    `${file}: 没有给出第二条可核对的检验（记录倒填）`,
  );

  // ── 4. 反过度修正：不是给这种人免罪 ────────────────────────────────────────
  assert.match(
    c,
    /这条不是禁止怀疑他，是禁止把顺序本身当证据/,
    `${file}: 缺少护栏，会变成"前民后神一律不许怀疑"`,
  );

  // ── 5. 它依赖的几块前提必须还在，否则这条会悬空 ────────────────────────────
  assert.ok(c.includes('【身份声明同标尺】'), `${file}: 身份声明同标尺被删了`);
  assert.ok(c.includes('【零成本行为不分阵营'), `${file}: 零成本行为那条被删了`);
  assert.ok(src.includes('【先后手不是身份公式】'), `${file}: 先后手不是身份公式被删了`);
  assert.ok(
    src.includes('也可以暂缓、部分披露或使用符合规则的公开假口径'),
    `${file}: 藏身份神职的假口径授权被删了，这条的理由②会失去依据`,
  );
  // 改口本身仍然是 C 级，不能被这条顺手提级
  assert.match(c, /C级：单次口误、记错规则、措辞混乱、改口/, `${file}: 改口的 C 级定档被改动了`);

  // ── 6. 位置：必须挂在【身份声明同标尺】之后，它是那条的推论 ─────────────────
  const iStd = c.indexOf('【身份声明同标尺】');
  const iOrder = c.indexOf('【「前面自报平民、后面跳神」不是狼点');
  assert.ok(iOrder > iStd, `${file}: 这条跑到了【身份声明同标尺】前面，读起来失去依据`);
}

